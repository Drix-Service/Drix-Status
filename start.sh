#!/usr/bin/env bash
#
# Start the whole Drix Status stack for local development:
#   Postgres + Redis (Docker) → main server → workers → status page + admin panel
#
# Usage: ./start.sh [--workers N] [--no-web] [--no-agents] [--help]
#   --workers N   local test workers to run (default 5, or TEST_WORKERS in .env)
#   --no-agents   start no workers at all
#   Website ports default to 3000/3001; busy ports move to the next free one.
#
# Test workers (test-worker-1 … N) are registered automatically and get a fresh
# token on every start. Real workers can be added too, with tokens from
# Admin → Workers → Add worker, set in .env as DRIX_AGENT_TOKENS=drx_aaa,drx_bbb
#
# Press Ctrl+C to stop everything this script started. Postgres and Redis keep
# running so the next start is instant (stop them with: make infra-down).
#
# Written for the bash 3.2 that ships with macOS, so no bash 4 features.

set -euo pipefail
cd "$(dirname "$0")"
ROOT="$(pwd)"
LOG_DIR="${DRIX_LOG_DIR:-$ROOT/.logs}"
COMPOSE=(docker compose -f deploy/docker-compose.yml)

WITH_WEB=1
WITH_AGENTS=1
WORKERS_FLAG=""
while [ $# -gt 0 ]; do
  case "$1" in
    --no-web) WITH_WEB=0 ;;
    --no-agents) WITH_AGENTS=0 ;;
    --workers)
      [ $# -ge 2 ] || { echo "--workers needs a number" >&2; exit 2; }
      WORKERS_FLAG="$2"
      shift
      ;;
    --workers=*) WORKERS_FLAG="${1#*=}" ;;
    -h | --help)
      sed -n '2,18p' "$0" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *)
      echo "Unknown option: $1 (try --help)" >&2
      exit 2
      ;;
  esac
  shift
done

# ---------- output helpers ----------
if [ -t 1 ]; then
  B=$'\033[1m' DIM=$'\033[2m' G=$'\033[32m' Y=$'\033[33m' R=$'\033[31m' N=$'\033[0m'
else
  B="" DIM="" G="" Y="" R="" N=""
fi
step() { printf '%s›%s %s\n' "$B" "$N" "$*"; }
ok() { printf '  %s✓%s %s\n' "$G" "$N" "$*"; }
warn() { printf '  %s!%s %s\n' "$Y" "$N" "$*"; }
fail() {
  printf '%s✗ %s%s\n' "$R" "$*" "$N" >&2
  exit 1
}

# A port counts as taken if anything answers on IPv4 or IPv6 localhost.
port_in_use() { (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null || (exec 3<>"/dev/tcp/::1/$1") 2>/dev/null; }

# free_port <preferred>: the preferred port, or the next free one after it.
free_port() {
  local p=$1
  while port_in_use "$p"; do p=$((p + 1)); done
  echo "$p"
}

# wait_for <seconds> <description> <command...>
wait_for() {
  local secs=$1 what=$2
  shift 2
  local i=0
  until "$@" >/dev/null 2>&1; do
    i=$((i + 1))
    [ "$i" -ge $((secs * 2)) ] && return 1
    sleep 0.5
  done
}

# ---------- prerequisites ----------
step "Checking tools"
for cmd in docker go curl; do
  command -v "$cmd" >/dev/null 2>&1 || fail "'$cmd' is not installed"
done
if [ "$WITH_WEB" = 1 ]; then
  command -v pnpm >/dev/null 2>&1 || fail "'pnpm' is not installed (npm install -g pnpm), or use --no-web"
fi
ok "docker, go$([ "$WITH_WEB" = 1 ] && echo ", pnpm") found"

# ---------- configuration ----------
step "Loading configuration"
if [ ! -f .env ]; then
  cp .env.example .env
  warn "Created .env from .env.example. Change ADMIN_EMAIL / ADMIN_PASSWORD before the first real use."
fi
# A stable SECRET_KEY encrypts alert channel settings and the SMTP password.
# Generate one on first run; changing it later makes saved secrets unreadable.
if ! grep -q '^SECRET_KEY=..' .env; then
  sed -i.bak '/^SECRET_KEY=/d' .env && rm -f .env.bak
  printf '\n# Generated by start.sh: encrypts stored secrets. Keep it, and keep it private.\nSECRET_KEY=%s\n' "$(od -An -tx1 -N32 /dev/urandom | tr -d ' \n')" >>.env
  ok "Generated SECRET_KEY in .env"
fi
# Variables already set in the environment win over .env.
while IFS= read -r line || [ -n "$line" ]; do
  case "$line" in '' | \#*) continue ;; esac
  key="${line%%=*}"
  val="${line#*=}"
  key="$(printf '%s' "$key" | tr -d '[:space:]')"
  case "$key" in '' | *[!A-Za-z0-9_]*) continue ;; esac
  val="${val%\"}" val="${val#\"}" val="${val%\'}" val="${val#\'}"
  if [ -z "${!key+x}" ]; then export "$key=$val"; fi
done <.env

HTTP_ADDR="${HTTP_ADDR:-:8080}"
API_PORT="${HTTP_ADDR##*:}"
export HTTP_ADDR API_URL="http://localhost:${API_PORT}"
AGENT_SERVER_URL="${DRIX_SERVER_URL:-http://localhost:${API_PORT}}"
ok "API on :$API_PORT"

# Agents and PUBLIC_URL depend on the API port, so it must be free. Website
# ports just move to the next free one (override with STATUS_PORT / ADMIN_PORT).
port_in_use "$API_PORT" && fail "Port $API_PORT (API) is already in use. Is Drix already running? Stop it first."
if [ "$WITH_WEB" = 1 ]; then
  want_status="${STATUS_PORT:-3000}"
  STATUS_PORT="$(free_port "$want_status")"
  [ "$STATUS_PORT" != "$want_status" ] && warn "Port $want_status is busy, so the status page uses $STATUS_PORT"
  want_admin="${ADMIN_PORT:-3001}"
  [ "$want_admin" = "$STATUS_PORT" ] && want_admin=$((STATUS_PORT + 1))
  ADMIN_PORT="$(free_port "$want_admin")"
  [ "$ADMIN_PORT" = "$STATUS_PORT" ] && ADMIN_PORT="$(free_port $((STATUS_PORT + 1)))"
  [ "$ADMIN_PORT" != "$want_admin" ] && warn "Port $want_admin is busy, so the admin panel uses $ADMIN_PORT"
  export STATUS_PORT ADMIN_PORT VITE_STATUS_URL="${VITE_STATUS_URL:-http://localhost:${STATUS_PORT}}"
  # Links in emails (invites, subscriber confirmations) point at the dev sites.
  export STATUS_URL="${STATUS_URL:-http://localhost:${STATUS_PORT}}" ADMIN_URL="${ADMIN_URL:-http://localhost:${ADMIN_PORT}}"
fi
# In development all email goes to Mailpit unless SMTP is configured.
export SMTP_URL="${SMTP_URL:-smtp://localhost:1025?from=Drix%20Status%20%3Cstatus@drix.localhost%3E&tls=none}"

# ---------- Docker, Postgres, Redis, Mailpit ----------
step "Starting Postgres, Redis and Mailpit"
if ! docker info >/dev/null 2>&1; then
  case "$(uname -s)" in
    Darwin)
      warn "Docker isn't running. Starting Docker Desktop…"
      open -a Docker || fail "Could not start Docker Desktop"
      ;;
    *) fail "Docker isn't running. Start the Docker daemon and try again." ;;
  esac
  wait_for 120 docker docker info || fail "Docker did not start within 2 minutes"
  ok "Docker is running"
fi
"${COMPOSE[@]}" up -d postgres redis mailpit >/dev/null 2>&1 || fail "docker compose failed. Run '${COMPOSE[*]} up postgres redis mailpit' to see why."
healthy() { [ "$("${COMPOSE[@]}" ps --format '{{.Health}}' postgres redis 2>/dev/null | grep -c '^healthy$')" = 2 ]; }
wait_for 60 "databases" healthy || fail "Postgres/Redis did not become healthy. Check: ${COMPOSE[*]} logs"
ok "Postgres and Redis are healthy, Mailpit inbox at http://localhost:8025"

# ---------- build ----------
step "Building server and agent"
mkdir -p bin "$LOG_DIR"
go build -o bin/drix-server ./server/cmd/drix-server || fail "Server build failed"
go build -o bin/drix-agent ./agent/cmd/drix-agent || fail "Agent build failed"
ok "bin/drix-server, bin/drix-agent"

if [ "$WITH_WEB" = 1 ] && [ ! -x web/node_modules/.bin/vite ]; then
  step "Installing website dependencies"
  (cd web && pnpm install --frozen-lockfile >"$LOG_DIR/pnpm-install.log" 2>&1) || fail "pnpm install failed. See .logs/pnpm-install.log"
  ok "web dependencies installed"
fi

# ---------- process management ----------
PIDS=()
NAMES=()
LOGS=()
STOPPING=0

cleanup() {
  [ "$STOPPING" = 1 ] && return
  STOPPING=1
  trap - INT TERM EXIT
  echo
  step "Stopping"
  local i
  for ((i = ${#PIDS[@]} - 1; i >= 0; i--)); do
    kill "${PIDS[$i]}" 2>/dev/null || true
  done
  for pid in ${PIDS[@]+"${PIDS[@]}"}; do
    wait "$pid" 2>/dev/null || true
  done
  ok "Server, workers and websites stopped"
  printf '  %sPostgres, Redis and Mailpit are still running. Stop them with: make infra-down%s\n' "$DIM" "$N"
}
trap cleanup EXIT
trap 'exit 130' INT TERM

# launch <name> <logfile> <command...>
launch() {
  local name=$1 log=$2
  shift 2
  "$@" >"$log" 2>&1 &
  PIDS+=($!)
  NAMES+=("$name")
  LOGS+=("$log")
}

# ---------- main server ----------
step "Starting main server"
launch "server" "$LOG_DIR/server.log" ./bin/drix-server
server_up() { curl -sf "http://localhost:${API_PORT}/healthz"; }
if ! wait_for 45 "server" server_up; then
  tail -n 20 "$LOG_DIR/server.log" >&2 || true
  fail "Server did not start. Full log: .logs/server.log"
fi
ok "http://localhost:${API_PORT}"

# ---------- workers ----------
random_hex() { od -An -tx1 -N"$1" /dev/urandom | tr -d ' \n'; }
sha256_hex() {
  if command -v sha256sum >/dev/null 2>&1; then printf '%s' "$1" | sha256sum | cut -d' ' -f1
  else printf '%s' "$1" | shasum -a 256 | cut -d' ' -f1; fi
}

# register_test_worker <name>: create or update the worker row with a fresh
# token (only its SHA-256 hash is stored, like the admin panel does) and print
# the token. A worker you disabled in the admin panel stays disabled.
register_test_worker() {
  local name=$1 tok hash prefix
  tok="drx_$(random_hex 20)"
  hash="$(sha256_hex "$tok")"
  prefix="${tok:0:10}"
  local db="${DATABASE_URL:-postgres://drix:drix@localhost:5432/drix}"
  db="${db##*/}"
  db="${db%%\?*}"
  "${COMPOSE[@]}" exec -T postgres psql -U drix -d "$db" -v ON_ERROR_STOP=1 -qtA >/dev/null <<SQL || return 1
WITH updated AS (
  UPDATE agents SET token_hash = '$hash', token_prefix = '$prefix'
  WHERE name = '$name' RETURNING id
)
INSERT INTO agents (name, region, token_hash, token_prefix)
SELECT '$name', 'local', '$hash', '$prefix'
WHERE NOT EXISTS (SELECT 1 FROM updated);
SQL
  printf '%s' "$tok"
}

AGENT_COUNT=0
if [ "$WITH_AGENTS" = 1 ]; then
  step "Starting workers"
  TEST_WORKERS="${WORKERS_FLAG:-${TEST_WORKERS:-5}}"
  case "$TEST_WORKERS" in '' | *[!0-9]*) fail "--workers / TEST_WORKERS must be a number (got '$TEST_WORKERS')" ;; esac

  # Test workers: registered automatically, fresh token every start.
  i=1
  while [ "$i" -le "$TEST_WORKERS" ]; do
    name="test-worker-$i"
    tok="$(register_test_worker "$name")" || fail "Could not register $name in Postgres"
    launch "$name" "$LOG_DIR/$name.log" \
      env DRIX_SERVER_URL="$AGENT_SERVER_URL" DRIX_AGENT_TOKEN="$tok" ./bin/drix-agent
    AGENT_COUNT=$((AGENT_COUNT + 1))
    i=$((i + 1))
  done
  [ "$TEST_WORKERS" -gt 0 ] && ok "$TEST_WORKERS test worker(s): test-worker-1 … test-worker-$TEST_WORKERS"

  # Real workers from .env tokens.
  REAL=0
  TOKENS="${DRIX_AGENT_TOKENS:-${DRIX_AGENT_TOKEN:-}}"
  for tok in $(printf '%s' "$TOKENS" | tr ',' ' '); do
    REAL=$((REAL + 1))
    launch "worker-$REAL" "$LOG_DIR/agent-$REAL.log" \
      env DRIX_SERVER_URL="$AGENT_SERVER_URL" DRIX_AGENT_TOKEN="$tok" ./bin/drix-agent
  done
  AGENT_COUNT=$((AGENT_COUNT + REAL))
  [ "$REAL" -gt 0 ] && ok "$REAL worker(s) from DRIX_AGENT_TOKENS"

  if [ "$AGENT_COUNT" = 0 ]; then
    warn "No workers started, so no checks will run. Use --workers N or set DRIX_AGENT_TOKENS in .env"
  else
    # Wait until every worker has connected (best effort; logs say why if not).
    connected() { [ "$(grep -c 'agent connected' "$LOG_DIR/server.log")" -ge "$AGENT_COUNT" ]; }
    if wait_for 20 "workers" connected; then
      ok "all $AGENT_COUNT worker(s) connected to $AGENT_SERVER_URL"
    else
      warn "Not every worker connected yet. Check .logs/test-worker-*.log and .logs/agent-*.log"
    fi
  fi
fi

# ---------- websites ----------
if [ "$WITH_WEB" = 1 ]; then
  step "Starting websites"
  # Run vite directly (not via pnpm) so Ctrl+C reliably stops it.
  launch "status page" "$LOG_DIR/status-web.log" sh -c 'cd web && exec node_modules/.bin/vite --config apps/status/vite.config.ts'
  launch "admin panel" "$LOG_DIR/admin-web.log" sh -c 'cd web && exec node_modules/.bin/vite --config apps/admin/vite.config.ts'
  web_up() { curl -sf -o /dev/null "http://localhost:${STATUS_PORT}" && curl -sf -o /dev/null "http://localhost:${ADMIN_PORT}"; }
  wait_for 45 "websites" web_up || fail "Websites did not start. See .logs/status-web.log and .logs/admin-web.log"
  ok "status page and admin panel ready"
fi

# ---------- summary ----------
echo
printf '%sDrix Status is running%s\n' "$G$B" "$N"
[ "$WITH_WEB" = 1 ] && printf '  Status page   %shttp://localhost:%s%s\n' "$B" "$STATUS_PORT" "$N"
[ "$WITH_WEB" = 1 ] && printf '  Admin panel   %shttp://localhost:%s%s\n' "$B" "$ADMIN_PORT" "$N"
printf '  API           http://localhost:%s\n' "$API_PORT"
[ "$WITH_AGENTS" = 1 ] && printf '  Workers       %s\n' "$AGENT_COUNT"
printf '  Email inbox   http://localhost:8025   %s(Mailpit: every email lands here)%s\n' "$DIM" "$N"
LOG_SHOWN="${LOG_DIR#"$ROOT/"}"
printf '  Logs          %s/   %s(tail -f %s/server.log)%s\n' "$LOG_SHOWN" "$DIM" "$LOG_SHOWN" "$N"
echo
printf '%sPress Ctrl+C to stop.%s\n' "$DIM" "$N"

# ---------- supervise ----------
# If anything we started exits, report it and shut the rest down.
while true; do
  for i in "${!PIDS[@]}"; do
    if ! kill -0 "${PIDS[$i]}" 2>/dev/null; then
      echo
      printf '%s✗ %s stopped unexpectedly. Last lines of %s:%s\n' "$R" "${NAMES[$i]}" "${LOGS[$i]#"$ROOT/"}" "$N" >&2
      tail -n 15 "${LOGS[$i]}" >&2 || true
      exit 1
    fi
  done
  sleep 2
done
